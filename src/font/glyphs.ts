const ACCENTS = {
  acute: ['..#', '.#.'],
  grave: ['#..', '.#.'],
  circumflex: ['.#.', '#.#'],
  tilde: ['.#.#', '#.#.'],
} as const;

const ACCENTED: Readonly<Record<string, readonly [string, keyof typeof ACCENTS]>> = {
  Á: ['A', 'acute'], À: ['A', 'grave'], Â: ['A', 'circumflex'], Ã: ['A', 'tilde'],
  É: ['E', 'acute'], Ê: ['E', 'circumflex'], Í: ['I', 'acute'],
  Ó: ['O', 'acute'], Ô: ['O', 'circumflex'], Õ: ['O', 'tilde'], Ú: ['U', 'acute'],
};

function base(text: string): Glyph {
  const rows = text.split('/').map((r) => r || '.');
  return { rows, above: [], width: Math.max(...rows.map((r) => r.length)) };
}

/** Desloca linhas para centralizá-las em uma largura. */
const centered = (rows: readonly string[], width: number): string[] =>
  rows.map((r) => '.'.repeat(Math.max(0, Math.floor((width - r.length) / 2))) + r);

function buildGlyphs(): Map<string, Glyph> {
  const glyphs = new Map<string, Glyph>();
  for (const [char, text] of Object.entries(BASE)) glyphs.set(char, base(text));
  for (const [char, [letter, accent]] of Object.entries(ACCENTED)) {
    const g = glyphs.get(letter)!;
    glyphs.set(char, { ...g, above: centered(ACCENTS[accent], g.width) });
  }
  const c = glyphs.get('C')!;
  glyphs.set('Ç', { ...c, rows: [...c.rows, '..#..', '.##..'] });
  for (const [char, glyph] of [...glyphs]) {
    const lower = char.toLowerCase();
    if (lower !== char) glyphs.set(lower, glyph);
  }
  return glyphs;
}

export const GLYPHS: ReadonlyMap<string, Glyph> = buildGlyphs();
